-- member 스키마(MB-W01). 근거: Member 기준 명세 3.1·3.2, MB-D003, MB-D008.
-- 버전 번호는 날짜형(V<yyyymmdd>_<순번>)으로 모듈 사이 충돌을 피한다.

CREATE TABLE members (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50),               -- LOCAL 필수, GOOGLE은 NULL 가능(명세 3.1)
    password_hash  VARCHAR(255),              -- LOCAL 필수, GOOGLE은 NULL 가능
    email          VARCHAR(255) NOT NULL,
    email_verified BOOLEAN      NOT NULL,
    nickname       VARCHAR(50)  NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    account_type   VARCHAR(20)  NOT NULL,
    account_status VARCHAR(20)  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_members_username UNIQUE (username),
    CONSTRAINT ck_members_account_type CHECK (account_type IN ('LOCAL', 'GOOGLE')),
    CONSTRAINT ck_members_account_status CHECK (account_status IN ('PENDING', 'ACTIVE', 'DISABLED')),
    -- 일반 계정은 username과 password_hash가 필수다(명세 3.1)
    CONSTRAINT ck_members_local_credentials CHECK (
        account_type <> 'LOCAL' OR (username IS NOT NULL AND password_hash IS NOT NULL))
);

-- 일반 계정끼리만 이메일 중복을 금지한다. 전역 UNIQUE는 두지 않는다(명세 3.1, 일반·Google 자동 병합 금지)
CREATE UNIQUE INDEX ux_members_local_email ON members (email) WHERE account_type = 'LOCAL';

CREATE TABLE member_oauth_accounts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id        BIGINT       NOT NULL,
    provider         VARCHAR(30)  NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    email            VARCHAR(255),
    created_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_member_oauth_accounts_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT uk_member_oauth_accounts_provider_user UNIQUE (provider, provider_user_id)
);
